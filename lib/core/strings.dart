extension TrContext on BuildContext {
  /// Short helper: context.tr('read'). Rebuilds when the language changes.
  String tr(String key) {
    final lang = watch<SettingsController>().uiLang;
    return _strings[lang]?[key] ?? _strings['en']![key] ?? key;
  }

  /// Like tr(), but fills {placeholders}: context.trArgs('exRoot', {'root': 'برك'}).
  /// Only call it inside build(), like tr().
  String trArgs(String key, Map<String, String> args) {
    var text = tr(key);
    args.forEach((k, v) => text = text.replaceAll('{$k}', v));
    return text;
  }
}
